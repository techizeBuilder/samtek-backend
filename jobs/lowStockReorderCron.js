import { Item } from '../models/Inventory.js';
import PurchaseRequest from '../models/PurchaseRequest.js';
import QCJob from '../models/QCJob.js';
import { generatePurchaseRequestId } from '../services/storeFlowService.js';
import { resolveFabricationLines } from '../controllers/purchaseRequestController.js';
import { dimensionSignature } from '../services/fabricationDemandService.js';
import notificationService from '../services/notificationService.js';
import { getFreeQty } from '../services/materialReservationService.js';

// Material Flow — Low Stock Auto-Purchase sweep.
//
// Runs periodically (see server/index.js's cron registration) rather than
// hooking into any specific stock-decreasing action, because stock can drop
// through 9+ different places in this codebase (Store's transfer-to-
// production, bulk transfer, fabrication cutting, Store's own QC-routing
// deduction, Dispatch, Sales Invoice, Service-visit parts, Purchase Returns,
// manual stock adjustment) — a single sweep that re-checks every item
// catches all of them uniformly, instead of only whichever ones got an
// explicit hook. Every created request is pre-approved and goes straight to
// Purchase (source: 'Store', storeApproved: true), same as Store's own
// manual "Not Available" requests already work.
//
// "Already coming" (2026-10-17, bug B1): an item (or a fabrication size) is
// skipped while any STOCK request for it is still on its way in — not yet
// bought, on a PO, or received but its QC not decided (stock only goes up at
// QC pass). The old check counted only this cron's own requests in
// Pending/Approved/Ordered, so the 30-minute sweep after Store received
// Tool-A saw the stock still low and raised PR037 while 25 pieces sat in QC.
// Counts:
//   - this cron's requests, Store's manual ones, and a vendor's replacement
//     for rejected material (it copies the original's code/name);
//   - not requests bought for one production or sales order (storeOrderId /
//     saleItemId) — that material goes to the order, not back to free stock.
// When what was coming has passed QC and stock is still at/below minimum, the
// next sweep raises as before; a rejection the vendor refunds instead of
// replacing brings nothing more, so it doesn't block.
const ON_THE_WAY_STATUSES = ['Pending', 'Approved', 'Ordered'];
const QC_UNDECIDED = ['Draft', 'Pending', 'In Progress'];

const escapeRegex = (s) => String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Stock requests for `item` still on their way in. `inQcRequestIds`: ids of
// purchase requests whose QC job is undecided (loaded once per sweep).
async function requestsOnTheWay(item, inQcRequestIds) {
  // Same item match the RFQ board uses (resolveMasterItemId): code or exact
  // name; plus this cron's own reorderItemId.
  const match = [{ reorderItemId: item._id }];
  if (item.name) match.push({ productName: new RegExp(`^${escapeRegex(item.name.trim())}$`, 'i') });
  if (item.code) match.push({ itemId: item.code }, { materialCode: item.code });
  return PurchaseRequest.find({
    companyId: item.companyId,
    storeOrderId: null,
    saleItemId: null,
    $and: [
      { $or: match },
      { $or: [{ status: { $in: ON_THE_WAY_STATUSES } }, { status: 'Received', _id: { $in: inQcRequestIds } }] },
    ],
  }).select('requestId status fabricationDimensionLines').lean();
}

async function notifyCreated(request, companyId) {
  try {
    await notificationService.triggerStoreNotification({
      action: 'purchase_request_created',
      data: { requestId: request.requestId, productName: request.productName, priority: request.priority },
      targetCompanyId: companyId,
    });
  } catch (e) {
    console.error('[LowStockReorder] notification error:', e);
  }
}

// Non-fabrication branch: a single flat reorder against the item's own qty.
async function checkPlainItem(item, stats, inQcRequestIds) {
  // Free stock (2026-10-09, user decision): stock still reserved for orders
  // doesn't count toward the minimum.
  if (!item.materialFlow) return;
  if ((await getFreeQty(item._id, item.qty || 0, item.companyId)) > item.minStock) return;

  if ((await requestsOnTheWay(item, inQcRequestIds)).length) return;

  const requestId = await generatePurchaseRequestId();
  const request = await PurchaseRequest.create({
    requestId,
    productName: item.name,
    quantity: item.reorderQty,
    requestFromDepartment: 'Store',
    priority: 'Medium',
    companyId: item.companyId,
    source: 'Store',
    storeApproved: true,
    autoGenerated: true,
    reorderItemId: item._id,
    unit: item.purchaseUnit || item.unit || null,
    materialCode: item.code,
  });
  stats.created++;
  await notifyCreated(request, item.companyId);
}

// Fabrication branch: every non-leftover catalog dimensionVariant is its own
// independent flow — dedup matches on fabricationDimensionLines[0].values
// (content-based identity) rather than an ObjectId reference, because
// Item.dimensionVariants[]._id is NOT stable across item edits (see
// PurchaseRequest.js's reorderItemId comment for why).
async function checkFabricationVariants(item, stats, inQcRequestIds) {
  // Per size, free stock (2026-10-09): that size's pieces minus what's still
  // reserved for orders of that size.
  const flagged = [];
  for (const dv of item.dimensionVariants || []) {
    if (dv.isLeftover || !dv.materialFlow) continue;
    const free = await getFreeQty(item._id, dv.subStock || 0, item.companyId, { variantId: dv._id });
    if (free <= (dv.minStock || 0)) flagged.push(dv);
  }
  if (!flagged.length) return;

  // Every size still on its way (a request is one size since 2026-10-09;
  // older multi-size ones count for each of their sizes).
  const openSignatures = new Set(
    (await requestsOnTheWay(item, inQcRequestIds))
      .flatMap((pr) => (pr.fabricationDimensionLines || []).map((l) => dimensionSignature(l.values)))
  );

  for (const variant of flagged) {
    const sig = dimensionSignature(variant.values);
    if (openSignatures.has(sig)) continue;

    let resolved;
    try {
      resolved = await resolveFabricationLines(item, [{ values: variant.values, quantity: variant.reorderQty }]);
    } catch (err) {
      console.error(`[LowStockReorder] Skipping ${item.code} dimension ${sig}:`, err.message);
      continue;
    }
    const quantity = resolved.isMassUnit
      ? resolved.resolvedQuantity
      : resolved.lines.reduce((sum, l) => sum + l.quantity, 0);
    const unit = resolved.isMassUnit ? resolved.resolvedUnit : (item.purchaseUnit || item.unit || null);

    const requestId = await generatePurchaseRequestId();
    const request = await PurchaseRequest.create({
      requestId,
      productName: item.name,
      quantity,
      requestFromDepartment: 'Store',
      priority: 'Medium',
      companyId: item.companyId,
      source: 'Store',
      storeApproved: true,
      autoGenerated: true,
      reorderItemId: item._id,
      unit,
      materialCode: item.code,
      fabricationDimensionLines: resolved.lines,
    });
    stats.created++;
    await notifyCreated(request, item.companyId);
  }
}

// `companyId` limits the sweep to one company (tests); the cron sweeps all.
export async function runLowStockReorderSweep({ companyId = null } = {}) {
  const stats = { scanned: 0, created: 0 };
  // Purchase requests received but still waiting for QC — their stock isn't in yet.
  const inQcRequestIds = await QCJob.distinct('purchaseRequestId', {
    source: 'Purchase',
    status: { $in: QC_UNDECIDED },
    purchaseRequestId: { $ne: null },
    ...(companyId ? { company: companyId } : {}),
  });
  const items = await Item.find({
    ...(companyId ? { companyId } : {}),
    isDiscontinued: { $ne: true },
    purchase: true,
    $or: [
      { materialFlow: { $in: ['High Flow', 'Medium Flow', 'Low Flow'] } },
      { 'dimensionVariants.materialFlow': { $in: ['High Flow', 'Medium Flow', 'Low Flow'] } },
    ],
  });

  for (const item of items) {
    stats.scanned++;
    try {
      if (item.fabricationRef) {
        await checkFabricationVariants(item, stats, inQcRequestIds);
      } else {
        await checkPlainItem(item, stats, inQcRequestIds);
      }
    } catch (err) {
      console.error(`[LowStockReorder] Error processing item ${item.code}:`, err);
    }
  }

  console.log(`[LowStockReorder] Sweep complete — scanned ${stats.scanned} item(s), created ${stats.created} purchase request(s).`);
  return stats;
}
