/**
 * One-time migration — one RFQ/PO card per fabrication size (procurement-v2, 2026-10-09)
 *
 * From now on a fabrication purchase request carries ONE size, and RFQ/PO
 * keeps one Open item group per item + size (ordered in pieces, kg
 * calculated). This brings existing data in line:
 *
 *  1. Requests not yet on a PO that carry several sizes are split: the first
 *     size stays on the request (quantity recomputed), every other size
 *     becomes a new request (new PR number, same item / priority / source /
 *     store order). Requests already on a PO are history — left alone.
 *  2. Item groups: the old unique index { item, unit } is dropped (it would
 *     block a second size card for the same item); every Open group gets its
 *     size fields (sizeKey '' for non-fabrication items — unchanged
 *     behaviour). An Open fabrication group holding requests of several
 *     sizes keeps only those of its first size; the others are freed and get
 *     their own card automatically the next time RFQ/PO loads. A fabrication
 *     group's quantity is recalculated from its pieces (so a quote at the old
 *     quantity shows as needing a sync / re-quote).
 *  3. The new unique index { item, unit, sizeKey } (Open only) is created.
 *
 * Dry run by default — prints what it would do. Run with --apply to write.
 * Needs the real MONGODB_URI (server/.env).
 * Run: node scripts/splitFabricationRequestsBySize.js [--apply]
 */

import connectDB from '../config/database.js';
import PurchaseRequest from '../models/PurchaseRequest.js';
import ItemQuoteGroup from '../models/ItemQuoteGroup.js';
import { Item } from '../models/Inventory.js';
import { dimensionSignature } from '../services/fabricationDemandService.js';
import { splitFabricationLinesPerSize } from '../controllers/purchaseRequestController.js';
import { resolveMasterItemId } from '../controllers/purchaseQuoteController.js';
import { prSizeKey, kgForPieces } from '../controllers/itemQuoteGroupController.js';

const ITEM_FIELDS = 'name unit purchaseUnit purchaseUnitType dimensionVariants fabricationRef';
// Everything on the original is copied onto the new per-size requests except
// these (identity, its own size / quantity, and anything about an order or
// receipt — they're not ordered yet).
const NOT_COPIED = ['_id', '__v', 'requestId', 'createdAt', 'updatedAt', 'quantity', 'unit',
  'fabricationDimensionLines', 'purchaseOrder', 'receivedAt', 'receivedFabricationLines', 'receivedQuantity', 'autoGenerated'];

async function nextRequestId(taken) {
  let n = (await PurchaseRequest.countDocuments({})) + 1;
  for (;;) {
    const candidate = `PR${String(n).padStart(3, '0')}`;
    if (!taken.has(candidate) && !(await PurchaseRequest.exists({ requestId: candidate }))) {
      taken.add(candidate);
      return candidate;
    }
    n++;
  }
}

export async function splitFabricationRequestsBySize({ apply = false } = {}) {
  const log = [];
  const taken = new Set();

  // ── 1. Requests with several sizes, not yet ordered ──────────────────────
  const multi = await PurchaseRequest.find({ 'fabricationDimensionLines.1': { $exists: true }, purchaseOrder: null });
  let requestsSplit = 0;
  let requestsCreated = 0;
  for (const pr of multi) {
    const sizes = new Set(pr.fabricationDimensionLines.map(l => dimensionSignature(l.values)));
    if (sizes.size < 2 && pr.fabricationDimensionLines.length < 2) continue;
    const itemId = await resolveMasterItemId(pr, pr.companyId);
    const masterItem = itemId ? await Item.findById(itemId).select(ITEM_FIELDS).lean() : null;
    if (!masterItem) { log.push(`SKIP ${pr.requestId}: its item can't be found`); continue; }
    let perSize;
    try {
      perSize = await splitFabricationLinesPerSize(masterItem, pr.fabricationDimensionLines, { requireCatalogMatch: false, fallbackUnit: pr.unit });
    } catch (err) {
      log.push(`SKIP ${pr.requestId}: ${err.message}`);
      continue;
    }
    if (perSize.length < 2) {
      // Same size listed twice — just merge it into one line.
      log.push(`MERGE ${pr.requestId}: same size listed twice → one line`);
      if (apply) {
        pr.fabricationDimensionLines = perSize[0].lines;
        pr.quantity = perSize[0].quantity;
        pr.unit = perSize[0].unit;
        await pr.save();
      }
      continue;
    }
    requestsSplit++;
    const [first, ...rest] = perSize;
    const newIds = [];
    for (const size of rest) {
      const requestId = await nextRequestId(taken);
      newIds.push(requestId);
      requestsCreated++;
      if (apply) {
        const copy = pr.toObject();
        for (const k of NOT_COPIED) delete copy[k];
        await PurchaseRequest.create({
          ...copy,
          requestId,
          autoGenerated: false,
          quantity: size.quantity,
          unit: size.unit,
          fabricationDimensionLines: size.lines,
        });
      }
    }
    log.push(`SPLIT ${pr.requestId} (${pr.productName}): keeps ${first.lines[0].quantity} pcs of one size; new ${newIds.join(', ')}`);
    if (apply) {
      pr.fabricationDimensionLines = first.lines;
      pr.quantity = first.quantity;
      pr.unit = first.unit;
      await pr.save();
    }
  }

  // ── 2. Item groups ───────────────────────────────────────────────────────
  const indexes = await ItemQuoteGroup.collection.indexes();
  const oldIndex = indexes.find(ix => JSON.stringify(ix.key) === JSON.stringify({ item: 1, unit: 1 }));
  if (oldIndex) {
    log.push(`DROP index ${oldIndex.name}`);
    if (apply) await ItemQuoteGroup.collection.dropIndex(oldIndex.name);
  }

  const open = await ItemQuoteGroup.find({ status: 'Open' });
  let groupsUpdated = 0;
  for (const g of open) {
    // Re-read the requests AFTER the split above (a split request now has one size).
    const prs = await PurchaseRequest.find({ _id: { $in: g.purchaseRequests } });
    const firstKey = prs.length ? prSizeKey(prs[0]) : '';
    if (!firstKey) {
      if (g.sizeKey !== '') {
        g.sizeKey = '';
        if (apply) await g.save();
      }
      continue;
    }
    const keep = prs.filter(pr => prSizeKey(pr) === firstKey);
    const freed = prs.filter(pr => prSizeKey(pr) !== firstKey);
    const requestedPieces = keep.reduce((sum, pr) => sum + (pr.fabricationDimensionLines || []).reduce((s, l) => s + (Number(l.quantity) || 0), 0), 0);
    const masterItem = await Item.findById(g.item).select(ITEM_FIELDS).lean();
    const sizeValues = keep[0].fabricationDimensionLines[0].values;
    let quantity = g.quantity;
    try {
      quantity = (await kgForPieces(masterItem, sizeValues, requestedPieces)).quantity;
    } catch (err) {
      log.push(`WARN group ${g._id}: kept its quantity (${err.message})`);
    }
    log.push(`GROUP ${g._id} (${masterItem?.name}): size set, ${requestedPieces} pcs → ${quantity} ${g.purchaseUnit || ''}${freed.length ? `; freed ${freed.map(p => p.requestId).join(', ')} (other sizes)` : ''}${quantity !== g.quantity ? ` (was ${g.quantity})` : ''}`);
    groupsUpdated++;
    if (apply) {
      g.purchaseRequests = keep.map(p => p._id);
      g.sizeKey = firstKey;
      g.sizeValues = sizeValues;
      g.requestedPieces = requestedPieces;
      g.pieces = requestedPieces;
      g.quantity = quantity;
      await g.save();
    }
  }

  // ── 3. The per-size index ─────────────────────────────────────────────────
  if (apply) {
    await ItemQuoteGroup.createIndexes();
    log.push('CREATE index { item, unit, sizeKey } (Open only)');
  } else {
    log.push('(would create index { item, unit, sizeKey } (Open only))');
  }

  return { apply, requestsWithSeveralSizes: multi.length, requestsSplit, requestsCreated, openGroups: open.length, groupsUpdated, log };
}

if (process.argv[1].includes('splitFabricationRequestsBySize')) {
  (async () => {
    try {
      await connectDB();
      const apply = process.argv.includes('--apply');
      console.log(apply ? '🔄 Applying the one-size-per-request split…' : '🔍 Dry run — nothing will be written (use --apply to write)…');
      const result = await splitFabricationRequestsBySize({ apply });
      for (const line of result.log) console.log('  ' + line);
      const { log, ...summary } = result;
      console.log('✅ Done:', JSON.stringify(summary, null, 2));
      process.exit(0);
    } catch (err) {
      console.error('❌ Failed:', err);
      process.exit(1);
    }
  })();
}
